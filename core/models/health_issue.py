"""
health_issue.py

Shared health issue model for all LegacyLens modules.

Health issues represent findings generated by:

- Photos
- Contacts
- Documents
- Email
- Calendar
- Knowledge

Health issues are consumed by:

- Archive Health Engine
- Reporting
- Scoring
- Dashboards
"""

from dataclasses import dataclass
from datetime import datetime


@dataclass(slots=True)
class HealthIssue:
    """
    Represents a single archive health finding.
    """

    issue_id: str

    module: str

    severity: str

    category: str

    title: str

    description: str

    recommendation: str = ""

    auto_fixable: bool = False

    confidence: float = 1.0

    created_at: datetime | None = None

    item_id: str = ""

    source_path: str = ""

    resolved: bool = False